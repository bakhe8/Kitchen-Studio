import assert from 'node:assert/strict';
import {stageCommands} from '../public/kitchen-stage-commands.js';
const doc={room:{},kitchen:{runs:[{id:'run'}],units:[{id:'rice',runId:'run'}]}};
const options=(route,details={})=>stageCommands(doc,route,details);
assert(options('cad').includes('library'));
assert(!options('project').includes('library'));
assert(options('cad').includes('libraries'),'the library manager is a drawing-screen command');
assert(!options('quote').includes('libraries')&&!options('survey',{wall:'right'}).includes('libraries'),'and not a command of the other screens');
assert.deepEqual(options('survey',{wall:'right'}),['file','wallPhoto','records']);
assert(!options('outline').includes('wallSheet'));assert(options('photo',{wall:'right'}).includes('wallSheet'));
assert(!options('survey').includes('wallPhoto'));
assert(!options('whole',{unitId:'rice',savedDesign:false}).includes('usage'));
assert(!options('whole',{unitId:'missing',savedDesign:true}).includes('usage'));
assert(options('whole',{unitId:'rice',savedDesign:true,canSetUsage:true}).includes('usage'));
assert(!options('whole',{unitId:'rice',savedDesign:true,canSetUsage:false}).includes('usage'));
assert(options('quote').includes('sheets')&&options('quote').includes('render'));
assert(!options('quote').includes('library')&&!options('quote').includes('history'));
assert(!stageCommands({room:{},kitchen:{runs:[],units:[]}},'quote').includes('render'));
assert.deepEqual(options('project'),['file']);
assert.deepEqual(options('factory'),['file']);
console.log('Toolbar follows stage, current wall, selected saved unit and available drawings.');
