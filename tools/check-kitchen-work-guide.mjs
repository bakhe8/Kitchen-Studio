import assert from 'node:assert/strict';
import {kitchenWorkGuide,answerGuideQuestion,guideQuickAnswers} from '../public/kitchen-work-guide.js';
import {approvalState,cleanWorkshop,releaseConcerns} from '../public/kitchen-workshop-state.js';
import {makeChainExample,attestChain,readChainRange} from '../public/kitchen-chain-model.js';
import {planWorkshopRow} from '../public/kitchen-production-row.js';
import {seedCatalog} from '../public/kitchen-workshop-factory.js';
import {confirmFixtureFitout} from './fixture-kitchen-fitout.mjs';

const tasks=r=>[...r.tasks,...r.later];
const start=await kitchenWorkGuide(null);assert.equal(start.current,start.tasks[0]);assert.equal(start.current.step,'outline');
const survey=makeChainExample(),w=survey.room.workshop,cat=seedCatalog();
cat.approved=true;cat.items.forEach(i=>{i.price=10;});
Object.assign(cat.terms,{worktop:'separate',labor:0,installation:0,delivery:0,marginPct:0,taxPct:0});
w.catalog=cat;
for(const wall of ['back','right'])w.chains[wall]=attestChain(survey,wall,w.chains[wall],{name:'قياس الاختبار',reference:'QA5'}).chain;
const g=planWorkshopRow(survey,{...readChainRange(survey,'back'),tier:'base',wanted:{sink:true,rice:false,dishwasher:false}});
assert.ok(g.ok,g.reason);
const doc=confirmFixtureFitout(g.doc),ws=doc.room.workshop;
const sign=async (d,key)=>{const state=await approvalState(d);d.room.workshop.approvals={...d.room.workshop.approvals,[key]:{key:state.keys[key],name:'QA',date:'2026-11-01'}};};
const missing=structuredClone(doc);delete missing.room.workshop.upstand;
const pick=(await kitchenWorkGuide(missing)).tasks.find(t=>t.id.startsWith('design.upstand.'));
assert(pick);assert.equal(guideQuickAnswers(missing,pick)[0].id,'none');
const chose=answerGuideQuestion(missing,pick,'none');assert(chose.ok);assert.equal(chose.doc.room.workshop.upstand.walls[pick.focus.wall].mode,'none');assert(!missing.room.workshop.upstand);
assert(!tasks(await kitchenWorkGuide(chose.doc)).some(t=>t.id===pick.id));assert.equal(answerGuideQuestion(chose.doc,pick,'none').ok,false);
assert(!tasks(await kitchenWorkGuide(doc)).some(t=>t.id.startsWith('base-')||t.id.startsWith('design.upstand')));
await sign(doc,'structure');
let r=await kitchenWorkGuide(doc);assert.equal(r.current.id,'finish.review');assert(r.current.facts.length>0);
const noDemo=structuredClone(doc);noDemo.room.workshop.catalog.approved=false;
assert(!tasks(await kitchenWorkGuide(noDemo)).some(t=>t.id==='finish.review'));
const explicit=structuredClone(doc);explicit.room.workshop.finishes={frontSku:'FACE-6-W'};
assert(!tasks(await kitchenWorkGuide(explicit)).some(t=>t.id==='finish.review'),'an existing effective selection should not be asked again');
assert.equal(answerGuideQuestion(explicit,r.current,'keep').ok,false,'outdated confirmation cannot approve different finishes');
const permuted=structuredClone(doc);
permuted.room.workshop.finishes={hardwareUnits:{},partUnits:{}};
const originalPrompt=(await kitchenWorkGuide(permuted)).current;
permuted.room.workshop.finishes={partUnits:{},hardwareUnits:{}};
assert.equal((await kitchenWorkGuide(permuted)).current.reviewKey,originalPrompt.reviewKey,'field order alone cannot reopen finish approval');
const approved=answerGuideQuestion(doc,r.current,'keep');assert(approved.ok);
assert(cleanWorkshop(approved.doc.room.workshop).guideFinishReview);
assert.equal(cleanWorkshop({...ws,guideFinishReview:'false'}),null);
const prev=await approvalState(doc),after=await approvalState(approved.doc);
assert.deepEqual(after.keys,prev.keys,'keeping existing finishes is workflow evidence, not a new factory order');
r=await kitchenWorkGuide(approved.doc);assert.equal(r.current.id,'production:customer');
const noPrice=structuredClone(approved.doc);noPrice.room.workshop.catalog.items.find(i=>i.sku==='AL-20').price=null;
r=await kitchenWorkGuide(noPrice);assert.equal(r.current.actor,'factory');assert.equal(r.current.focus.sku,'AL-20');assert(!tasks(r).some(t=>t.id==='finish.review'));
await sign(approved.doc,'customer');r=await kitchenWorkGuide(approved.doc);assert.equal(r.current.id,'production:release');
await sign(approved.doc,'release');r=await kitchenWorkGuide(approved.doc);assert.equal(r.complete,true);assert.equal(r.current,null);
assert.deepEqual(releaseConcerns(approved.doc,await approvalState(approved.doc)),[]);
console.log('Global guide: real 5×5 drawing, scoped answers, retained defaults, stale answers rejected, price assigned to factory, customer signature, production release and real handoff.');
