import assert from 'node:assert/strict';
import {addFeature,addUnit} from '../public/kitchen-model.js';
import {applyChain,chainFromDrawing,makeChainExample,readChainRange} from '../public/kitchen-chain-model.js';
import {applyWallOptions,buildUpperRows,cleanChainOptions,readWallOptions,wallOptionTakeoff,wallUpperBands} from '../public/kitchen-chain-options.js';
let d=makeChainExample();
const identified=d.kitchen.features.find(f=>f.kind==='window').id;
const o=structuredClone(readWallOptions(d,'back'));
o.curtains[identified]={state:'factory',type:'roller',leftMm:100,rightMm:200,aboveMm:100,dropMm:1150,projectionMm:100};
o.cornice={enabled:true,heightMm:50,projectionMm:80,returns:true,reviewed:true};
o.mode='two';
const change=applyWallOptions(d,'back',o);
assert.ok(change.ok,change.reason);
d=change.doc;
assert.deepEqual(cleanChainOptions(d.room.workshop.options),d.room.workshop.options);
const rg=readChainRange(d,'back');
assert.deepEqual(rg.baseSpans,[{startMm:1300,endMm:4300}]);
assert.deepEqual(rg.upperSpans,[{startMm:1300,endMm:1900},{startMm:3400,endMm:4300}]);
assert.deepEqual(rg.upperBandSpans[1],[{startMm:1300,endMm:4300}]);
assert.deepEqual(wallUpperBands(d,'back'),[{bottom:145,height:90,depth:34},{bottom:235,height:40,depth:34}]);
const made=buildUpperRows(d,'back');assert.ok(made.ok,made.reason);assert.equal(made.count,3);assert.equal(made.doc.kitchen.runs.length,3);
assert.ok(buildUpperRows(made.doc,'back').ok);assert.equal(buildUpperRows(made.doc,'back').doc.kitchen.units.length,made.doc.kitchen.units.length);
const take=wallOptionTakeoff(made.doc,'back');assert.deepEqual(take.pending,[]);assert.equal(take.items.find(i=>i.kind==='cornice').quantity,3.68);
assert.equal(take.items.find(i=>i.kind==='curtain').quantity,1);
const withHeat=addFeature(d.kitchen,d.room,{id:'heater-real',kind:'heater',wall:'left',u:160,bottom:160,width:40,height:50});
assert.ok(withHeat.ok);const hDoc={...d,kitchen:withHeat.kitchen};
const h=readWallOptions(hDoc,'left');h.heaters['heater-real']={state:'cover',model:'',reviewed:false,leftMm:null,rightMm:null,aboveMm:null,belowMm:null,frontMm:null};
const approved=applyWallOptions(hDoc,'left',h);assert.ok(approved.ok);
const pending=wallOptionTakeoff(approved.doc,'left');assert.equal(pending.items[0].readiness,'review');assert.ok(pending.pending[0].includes('السخان'));
const changed=structuredClone(readWallOptions(made.doc,'back'));changed.mode='tall';
const after=applyWallOptions(made.doc,'back',changed);
assert.ok(wallOptionTakeoff(after.doc,'back').pending.some(s=>s.includes('توليد')));
const first=made.doc.kitchen.runs[0],custom=addUnit(made.doc.kitchen,made.doc.room,{kind:'storage',runId:first.id,u:first.start,width:40});assert.ok(custom.ok,custom.reason);
const fixed=applyWallOptions({...made.doc,kitchen:custom.kitchen},'back',changed);
assert.equal(buildUpperRows(fixed.doc,'back').ok,false);
const noChains={...d,room:{...d.room,workshop:{}}},adopted=chainFromDrawing(noChains,'back');
assert.equal(adopted.source,'drawing');assert.ok(adopted.rows.every(r=>r.featureId));
const adoptedDoc=applyChain(noChains,'back',adopted);assert.ok(adoptedDoc.ok,adoptedDoc.reason);assert.equal(adoptedDoc.doc.kitchen.features.length,d.kitchen.features.length);
const movedDoc={...d,kitchen:{...d.kitchen,features:d.kitchen.features.map(f=>f.id===identified?{...f,u:f.u+1}:f)}};
assert.equal(readChainRange(movedDoc,'back'),null);assert.equal(applyChain(movedDoc,'back',d.room.workshop.chains.back).stale,true);
assert.ok(applyChain(movedDoc,'back',d.room.workshop.chains.back,{restoreModified:true}).ok);
console.log('Curtain envelope by height, multiple upper storeys and safe regeneration, crown takeoff, heater model gate, linked feature adoption and CAD divergence.');
