import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {seedCatalog,cleanCatalog,getFactoryCatalog,buildFactoryQuote} from '../public/kitchen-workshop-factory.js';
import {cleanWorkshop,approvalState,releaseConcernGroups} from '../public/kitchen-workshop-state.js';
import {catalogFingerprint} from '../public/kitchen-factory-template.js';
import {makeChainExample,attestChain,readChainRange} from '../public/kitchen-chain-model.js';
import {planWorkshopRow} from '../public/kitchen-production-row.js';
import {confirmFixtureFitout} from './fixture-kitchen-fitout.mjs';

const coldModel=spawnSync(process.execPath,['--input-type=module','-e',`await import(${JSON.stringify(new URL('../public/kitchen-model.js',import.meta.url).href)})`],{encoding:'utf8'});
assert.equal(coldModel.status,0,'The geometry model must load independently of catalog validation: '+coldModel.stderr);
const legacy=seedCatalog();legacy.approved=true;legacy.revision=7;legacy.layoutRevision=3;
legacy.items.forEach(i=>i.price=10);
Object.assign(legacy.terms,{labor:0,installation:0,delivery:0,marginPct:0,taxPct:0});
const clean=cleanCatalog(legacy),migrated=cleanWorkshop({catalog:legacy});
assert(migrated?.storeCatalog,'Legacy catalogs must migrate into independent store records.');
const {catalogRecordsFromWorkshop,normalizeWorkshopCatalogs,reconcileWorkshopCatalogs,approveWorkshopCatalogRecord,catalogRecordStates}=await import('../public/kitchen-catalog-records.js');
assert.deepEqual(migrated.catalog,clean,'The legacy calculation view must be byte-for-byte stable after cleaning.');
assert.equal(catalogFingerprint(migrated.catalog),catalogFingerprint(legacy));
assert.equal(migrated.storeCatalog.items[0].price,10,'Purchase prices belong to the store.');
assert(!('terms' in migrated.storeCatalog));assert(!('items' in migrated.factoryRecipes));
assert(!('prices' in migrated.pricingTerms));assert(!('families' in migrated.pricingTerms));
assert(!Object.keys(migrated).includes('catalog'));
const stored=JSON.parse(JSON.stringify(migrated));assert(!('catalog' in stored));
assert.deepEqual(getFactoryCatalog({room:{workshop:stored}}),clean);
assert.deepEqual(normalizeWorkshopCatalogs(stored).catalog,clean);
assert.deepEqual(catalogRecordStates(migrated),{store:{revision:7,approved:true},factory:{revision:7,approved:true},pricing:{revision:7,approved:true}});
assert.equal(cleanWorkshop({storeCatalog:stored.storeCatalog}),null,'Partial separated catalogs fail closed.');
assert.equal(cleanWorkshop({...stored,pricingTerms:{...stored.pricingTerms,revision:0}}),null);
assert.equal(cleanWorkshop({...stored,catalog:{...clean,items:clean.items.map((i,n)=>n?i:{...i,price:20})}}),null,'Untrusted conflicting dual formats fail closed.');
assert(cleanWorkshop({...stored,catalog:clean}),'Matching dual-format files remain readable.');

const priceEdit={...clean,revision:8,approved:false,items:clean.items.map((i,n)=>n?i:{...i,price:11})};
const afterPrice=reconcileWorkshopCatalogs({...stored,catalog:priceEdit},migrated);
assert(afterPrice);assert.equal(afterPrice.storeCatalog.revision,8);assert.equal(afterPrice.storeCatalog.approved,false);
assert.deepEqual(afterPrice.factoryRecipes,migrated.factoryRecipes,'Changing a purchase price must preserve factory recipes and approval.');
assert.deepEqual(afterPrice.pricingTerms,migrated.pricingTerms);
assert.equal(afterPrice.catalog.approved,true,'The compatibility approval describes the factory only.');
assert.equal(afterPrice.catalog.items[0].price,11);
assert.equal(migrated.catalog.items[0].price,10,'Helpers must not mutate source records.');
const approvedStore=approveWorkshopCatalogRecord(afterPrice,'store');assert.equal(approvedStore.storeCatalog.approved,true);
assert.deepEqual(approvedStore.factoryRecipes,afterPrice.factoryRecipes);
assert.equal(approveWorkshopCatalogRecord(afterPrice,'unknown'),null);
assert.equal(approveWorkshopCatalogRecord(afterPrice,['store']),null);

const technical={...clean,revision:8,approved:false,items:clean.items.map((i,n)=>n?i:{...i,thicknessMm:21})};
const afterTechnical=reconcileWorkshopCatalogs({...stored,catalog:technical},migrated);
assert(afterTechnical);assert.equal(afterTechnical.factoryRecipes.approved,false);
assert.equal(afterTechnical.factoryRecipes.revision,7,'An invalidated dependency does not edit the recipe payload.');
assert.equal(afterTechnical.pricingTerms.approved,true);
// Front alternatives may be picked by the project without appearing as a SKU
// in a recipe. Their engineering is still covered by factory approval.
const selectedAlternative=normalizeWorkshopCatalogs({...stored,finishes:{frontSku:'FACE-6-G'}});
const alternativeEdit=structuredClone(clean);alternativeEdit.revision++;alternativeEdit.approved=false;
alternativeEdit.items.find(i=>i.sku==='FACE-6-G').stockLengthMm=3000;
const afterAlternative=reconcileWorkshopCatalogs({...selectedAlternative,catalog:alternativeEdit},selectedAlternative);
assert.equal(afterAlternative.factoryRecipes.approved,false,'Engineering of the selected front alternative invalidates factory approval.');
assert.equal(afterAlternative.factoryRecipes.revision,7);
assert.equal(reconcileWorkshopCatalogs({...stored,catalog:alternativeEdit},migrated).factoryRecipes.approved,false,'Unrestricted recipe front alternatives are part of factory approval before they are selected.');
const alternativePrice=structuredClone(clean);alternativePrice.items.find(i=>i.sku==='FACE-6-G').price=17;
assert.equal(reconcileWorkshopCatalogs({...selectedAlternative,catalog:alternativePrice},selectedAlternative).factoryRecipes.approved,true,'Alternative purchase prices remain the store responsibility.');
const spare=structuredClone(clean);spare.items.push({...spare.items.find(i=>i.sku==='BODY-6'),sku:'SPARE-BODY',name:'Unused spare'});
const spareWorkshop=normalizeWorkshopCatalogs({catalog:spare}),spareEdit=structuredClone(spareWorkshop.catalog);
spareEdit.items.find(i=>i.sku==='SPARE-BODY').thicknessMm=8;
assert.equal(reconcileWorkshopCatalogs({...spareWorkshop,catalog:spareEdit},spareWorkshop).factoryRecipes.approved,true,'Engineering of an unused, ineligible store item does not revoke factory approval.');
const termsEdit={...clean,revision:8,approved:false,terms:{...clean.terms,labor:100}};
const afterTerms=reconcileWorkshopCatalogs({...stored,catalog:termsEdit},migrated);
assert.equal(afterTerms.pricingTerms.revision,8);assert.equal(afterTerms.pricingTerms.approved,false);
assert.deepEqual(afterTerms.storeCatalog,migrated.storeCatalog);assert.deepEqual(afterTerms.factoryRecipes,migrated.factoryRecipes);
const recipeEdit=structuredClone(clean);recipeEdit.revision++;recipeEdit.approved=false;recipeEdit.families.storage.recipe[0].count++;
const afterRecipe=reconcileWorkshopCatalogs({...stored,catalog:recipeEdit},migrated);
assert.equal(afterRecipe.factoryRecipes.revision,8);assert.equal(afterRecipe.factoryRecipes.approved,false);
assert.deepEqual(afterRecipe.storeCatalog,migrated.storeCatalog);assert.deepEqual(afterRecipe.pricingTerms,migrated.pricingTerms);
assert.deepEqual(catalogRecordsFromWorkshop(reconcileWorkshopCatalogs({...stored,activeWall:'back'},migrated)),catalogRecordsFromWorkshop(migrated));

const d=makeChainExample();d.room.workshop.catalog=clean;
d.room.workshop.chains.back=attestChain(d,'back',d.room.workshop.chains.back,{name:'QA',reference:'records'}).chain;
const row=planWorkshopRow(d,{...readChainRange(d,'back'),tier:'base',wanted:{rice:false,sink:false,dishwasher:false}});assert(row.ok,row.reason);
const doc=row.doc;confirmFixtureFitout(doc);
const beforeQuote=buildFactoryQuote(doc),beforeState=await approvalState(doc);
const splitDoc={...doc,room:{...doc.room,workshop:cleanWorkshop(doc.room.workshop)}};
assert.deepEqual(buildFactoryQuote(splitDoc),beforeQuote,'Migration preserves every quote field and calculation.');
assert.deepEqual((await approvalState(splitDoc)).keys,beforeState.keys,'Migration preserves all project approval signatures.');
const pending=normalizeWorkshopCatalogs({...JSON.parse(JSON.stringify(splitDoc.room.workshop)),storeCatalog:{...splitDoc.room.workshop.storeCatalog,approved:false}});
const pendingDoc={...splitDoc,room:{...splitDoc.room,workshop:pending}},pendingQuote=buildFactoryQuote(pendingDoc);
assert.equal(pendingQuote.approved,true);assert.equal(pendingQuote.ready,false,'All owner approvals are required before release.');
const groups=releaseConcernGroups(pendingDoc,{valid:{customer:true},quote:pendingQuote});
assert(groups.some(g=>g.issues.some(s=>s.includes('المتجر'))),'The release reason names the pending store approval.');
console.log('Catalog records: lossless legacy migration, canonical persistence, invalid dual/partial rejection, independent revisions and approvals, dependency invalidation, quote and approval signature parity.');
