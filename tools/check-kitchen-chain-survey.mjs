// The villa shown in the wall visit has both a proposed cooker hood and a
// separate exhaust service. The recorded service's centre is above the frame.
const villa=makeFurnishedSaudiRoom('villa'),proposal=chainFromDrawing(villa,'back');
const aperture={...newChainRow('vent','duct'),from:'origin',gapMm:3420,bottomMm:2470,widthMm:240,heightMm:240};
proposal.rows.push(aperture);
const originals=structuredClone(villa.kitchen);
assert.deepEqual(applyChain(villa,'back',proposal).designConflicts,[]);
proposal.rows[0].gapMm=2740;
const movedVilla=applyChain(villa,'back',proposal);
assert(movedVilla.ok,movedVilla.reason);
const win=movedVilla.features.find(f=>f.kind==='window'),hood=villa.kitchen.units.find(u=>u.kind==='hood'),ductId='chain-back-duct';
assert.equal(win.u,274);assert.equal(movedVilla.features.find(f=>f.id===ductId).bottom,235);
assert.deepEqual(movedVilla.designConflicts.map(c=>[c.type,...c.ids]),[['body-feature',hood.id,win.id]]);
assert.deepEqual(villa.kitchen,originals);assert.deepEqual(movedVilla.doc.kitchen.units,villa.kitchen.units);
assert.equal(validateKitchenChange(villa.kitchen,villa.room,movedVilla.doc.kitchen,movedVilla.doc.room).ok,false);
assert(kitchenGeometry(movedVilla.doc.kitchen,movedVilla.doc.room).hardConflicts.some(c=>c.ids.includes(hood.id)&&c.ids.includes(win.id)));
assert.equal(applyChain(movedVilla.doc,'back',proposal).designConflicts.length,1,'retained conflict is visible on reopening measurements');
const relocated={...movedVilla.doc.kitchen,units:movedVilla.doc.kitchen.units.map(u=>u.id===hood.id?{...u,u:u.u-1}:u)};
assert.equal(validateSurveyFeatureChange(villa.kitchen,villa.room,relocated,villa.room,[win.id]).ok,false,'unit edits cannot use the survey exception');
const noHood={...villa,kitchen:{...villa.kitchen,units:villa.kitchen.units.filter(u=>u.id!==hood.id)}};
assert.deepEqual(applyChain(noHood,'back',proposal).designConflicts,[],'a separate and higher duct is compatible with the window');
const touching={...aperture,bottomMm:2170};
const withAperture=r=>({...proposal,rows:[...proposal.rows.slice(0,-1),r]});
assert(applyChain(noHood,'back',withAperture(touching)).ok,'touching edges have zero area');
