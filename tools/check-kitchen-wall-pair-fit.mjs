import {architectureWall} from '../public/kitchen-architecture.js';
import assert from 'node:assert/strict';
import {createKitchen} from '../public/kitchen-model.js';
import {applyChain,newChainRow,readChainRange,siteReleaseIssues} from '../public/kitchen-chain-model.js';
import {planWorkshopRow} from '../public/kitchen-production-row.js';
import {fillKitchenRow} from '../public/kitchen-row-fill.js';
import {compareKitchenLayouts} from '../public/kitchen-production-alternatives.js';
import {buildFactoryQuote,seedCatalog} from '../public/kitchen-workshop-factory.js';
import {wallPairDatum} from '../public/kitchen-wall-pair.js';
import {wallPairReleaseIssues,wallPairSpans,checkWallPairRow,wallPairJointIssue} from '../public/kitchen-wall-pair-fit.js';

const room={width:300,length:400,height:280,colors:{},name:'اختبار قياسي'};
const chain={source:'field',rows:[{...newChainRow('corner','end'),gapMm:3000}]};
const saved=applyChain({room,kitchen:createKitchen(room,'empty')},'back',chain);
assert.ok(saved.ok,saved.reason);
const baseline=saved.doc;
const pair={backMm:3000,frontMm:2980,heightMm:430,depthMm:600,datum:wallPairDatum(baseline,'back'),anchor:{side:'start',offsetMm:0}};
const change=(d,o={})=>({...d,room:{...d.room,workshop:{...d.room.workshop,wallPairs:{back:{base:{...pair,...o}}}}}});
const d=change(baseline);
const range=readChainRange(d,'back');
assert.deepEqual(range.baseSpans,[{startMm:0,endMm:2980}]);
assert.deepEqual(range.upperSpans,[{startMm:0,endMm:3000}]);
const hold=readChainRange(change(baseline,{anchor:undefined}),'back');
assert.deepEqual(hold.baseSpans,[{startMm:0,endMm:3000}],'no arbitrary placement without a datum');
assert.equal(hold.pairPending.base.limitMm,2980);assert(!hold.pairPending.upper);
const runPlan=planWorkshopRow(d,{...range,tier:'base'});
assert.ok(runPlan.ok,runPlan.reason);
const run=runPlan.doc.kitchen.runs.find(r=>r.id===runPlan.runId);
assert.deepEqual(runPlan.spans,[[0,2980]]);
assert.equal(runPlan.row.units.reduce((sum,u)=>sum+u.widthMm,0),2950);
assert(runPlan.row.warnings.some(w=>w.includes('فراغ 30 مم')));
const ambiguousConsent=planWorkshopRow(runPlan.doc,{runId:run.id,leavePairRemainder:'false'});
assert.ok(ambiguousConsent.ok);assert(ambiguousConsent.row.warnings.some(w=>w.includes('فراغ 30 مم')));
const accept=planWorkshopRow(runPlan.doc,{runId:run.id,leavePairRemainder:true});
assert.ok(accept.ok,accept.reason);assert(!accept.row.warnings.some(w=>w.includes('فراغ 30 مم')));
assert.deepEqual(accept.doc.kitchen.runs.find(r=>r.id===run.id).fillGaps,[{u:295,width:3}]);
const repeat=planWorkshopRow(accept.doc,{runId:run.id});
assert.ok(repeat.ok,repeat.reason);assert(!repeat.pairRemainder);assert.deepEqual(repeat.row.units,accept.row.units);
const custom=seedCatalog();custom.families.storage.stepMm=1;
const bespoke=planWorkshopRow(d,{...range,tier:'base'},custom);
assert.ok(bespoke.ok,bespoke.reason);assert.equal(bespoke.row.units.reduce((sum,u)=>sum+u.widthMm,0),2980);
const mirrored=change(baseline,{anchor:{side:'end',offsetMm:0}});
const fromRight=planWorkshopRow(mirrored,{...readChainRange(mirrored,'back'),tier:'base'});
assert.ok(fromRight.ok,fromRight.reason);assert.equal(Math.min(...fromRight.row.units.map(u=>u.startMm)),50);
assert(fromRight.row.warnings.some(w=>w.includes('20–50 مم')));
assert(runPlan.doc.kitchen.units.every(u=>u.u*10+u.width*10<=2980));
const cad=fillKitchenRow({...d.kitchen,runs:[run]},d.room,run.id);
assert.ok(cad.ok,cad.reason);assert.equal(Math.max(...cad.kitchen.units.map(u=>(u.u+u.width)*10)),2980);
const whole=await compareKitchenLayouts(d,{walls:['back'],wanted:{rice:false,sink:false,dishwasher:false}});
assert(whole.candidates.length,whole.reasons.join('/'));
assert(whole.candidates.every(c=>c.doc.kitchen.units.every(u=>(u.u+u.width)*10<=2980)));
const u={id:'edge',kind:'storage',runId:run.id,u:240,width:60},safe={...u,id:'safe',u:60};
const existing={...d,kitchen:{...runPlan.doc.kitchen,units:[u,safe]}};
assert(wallPairReleaseIssues(existing,{unitIds:['edge']}).length);
assert.deepEqual(wallPairReleaseIssues(existing,{unitIds:['safe']}),[]);
assert(siteReleaseIssues(existing,{unitIds:['edge']}).some(x=>x.includes('المجال المشترك')));
const quote=buildFactoryQuote(existing,{unitIds:['edge']});
assert(quote.releaseIssues.some(s=>s.includes('المجال المشترك')));
const edge=architectureWall(d.room,'back');
assert.equal(wallPairJointIssue(d.room,edge,'start','base',0,860),'');
assert(wallPairJointIssue(d.room,edge,'end','base',0,860).includes('زاوية'));
assert.equal(wallPairJointIssue(d.room,edge,'end','base',0,860,-20/600),'');
const unresolved=change(existing,{anchor:undefined});
assert(wallPairReleaseIssues(unresolved,{unitIds:['safe']}).some(v=>v.includes('طرف')));
const nearFront={...u,id:'near-front',u:0,width:298.1,modelSpec:{depthMm:600,heightMm:860}};
const shallow={...u,id:'shallow',u:50,width:30,modelSpec:{depthMm:350,heightMm:860}};
const uncertain=change(existing,{anchor:undefined,errorMm:1});
assert.deepEqual(checkWallPairRow(uncertain,run,[nearFront,shallow]).errors,[]);
assert(checkWallPairRow(unresolved,run,[nearFront,shallow]).errors.length);
const deep={...u,id:'deep',u:50,modelSpec:{depthMm:620,heightMm:860}};
assert(checkWallPairRow(d,run,[deep]).pending.some(v=>v.includes('أعمق')));
assert.deepEqual(wallPairSpans(d,{...run,tier:'upper',bottom:150,height:70},[{startMm:0,endMm:3000}]),[{startMm:0,endMm:3000}]);
assert.deepEqual(wallPairSpans(d,run,[{startMm:20,endMm:300},{startMm:1000,endMm:3000}]),[{startMm:20,endMm:300},{startMm:1000,endMm:2980}]);
assert.deepEqual(readChainRange(change(d,{frontMm:3000,anchor:{side:'start',offsetMm:20}}),'back').baseSpans,[{startMm:20,endMm:3000}]);
assert.deepEqual(readChainRange(change(d,{frontMm:3020}),'back').baseSpans,[{startMm:0,endMm:3000}]);
const manual=planWorkshopRow(existing,{runId:run.id});
assert.equal(manual.ok,false);assert.equal(manual.doc,existing);
assert.equal(existing.kitchen.units[0].u,240);
console.log('Paired wall bounds in CAD, measured spans, proposals, factory row, scoped release and immutable manual anchors verified.');
