import assert from 'node:assert/strict';
import {scenePlan} from '../public/kitchen-project.js';
import {getKitchenPhotoMesh,renderKitchenRoom} from '../public/kitchen-render.js';
import {makeVisitExample} from './fixture-kitchen-visit-example.mjs';
import {proposeWholeKitchen} from '../public/kitchen-whole-plan.js';
import {buildFactoryQuote} from '../public/kitchen-workshop-factory.js';

const {candidates}=await proposeWholeKitchen(makeVisitExample());
const doc=candidates[0].doc,workshop=doc.room.workshop;
const rice=doc.kitchen.units.find(u=>u.kind==='drawers'),sink=doc.kitchen.units.find(u=>u.kind==='sink');
const upper=doc.kitchen.units.find(u=>doc.kitchen.runs.find(r=>r.id===u.runId)?.tier==='upper');
const snapshot=()=>getKitchenPhotoMesh(scenePlan(doc.room),doc.kitchen);
const face=(mesh,u)=>mesh.faces.find(f=>f.id===u.id&&['drawer-front','door-front'].includes(f.tag));
const before=snapshot(),order=buildFactoryQuote(doc);
assert.equal(face(before,rice).partSku,'FACE-6-W');assert.equal(face(before,rice).color,'#f1efe8');
assert.equal(face(before,upper).partSku,'FACE-6-W');
assert(!before.faces.some(f=>f.kind==='dishwasher'&&f.partSku==='FACE-6-W'));
assert.equal(order.pieces.find(p=>p.unitId===rice.id&&p.label==='حشوة واجهة').sku,face(before,rice).partSku);
const firstRender=renderKitchenRoom(scenePlan(doc.room),{kitchen:doc.kitchen});
assert.match(firstRender.html,/data-room-light="floor"/);assert.match(firstRender.html,/data-room-light="wall"/);
assert.match(firstRender.html,/data:image\/jpeg;base64,/);assert(!firstRender.html.includes('garden_nook.webp'));
workshop.finishes={frontSku:'FACE-6-G',units:{[rice.id]:{frontSku:'FACE-6-W'}}};
const updated=snapshot();
assert.equal(face(updated,rice).color,face(before,rice).color);
assert.equal(face(updated,upper).partSku,'FACE-6-G');assert.equal(face(updated,sink).color,'#c5aa87');
assert.deepEqual(face(updated,sink).points,face(before,sink).points);
assert.equal(buildFactoryQuote(doc).pieces.find(p=>p.unitId===sink.id&&p.label==='حشوة واجهة').sku,face(updated,sink).partSku);
const legacy={...doc.room,workshop:undefined};
assert.equal(face(getKitchenPhotoMesh(scenePlan(legacy),doc.kitchen),rice).frontFinish,rice.frontFinish);
const projected=scenePlan(doc.room).room.frontAppearance;
assert(!JSON.stringify(projected).includes('price')&&!JSON.stringify(projected).includes('DEMO-DW60'));
console.log('Factory-priced front colours, inherited upper recipes, explicit per-unit exceptions, untouched appliance and free CAD, integrated physically scaled daylight/portable textures, unchanged dimensions.');
