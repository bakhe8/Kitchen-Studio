import assert from 'node:assert/strict';
import {cleanUpstandSpec,cleanUpstandProfiles,worktopUpstandTakeoff,setUpstandWindowChoice} from '../public/kitchen-worktop-upstand.js';
import {previewUpstandWindowChoice} from '../public/kitchen-worktop-upstand.js';

const stock={sku:'QSTONE',name:'حجر تجريبي',kind:'panel',colorHex:'#aabbcc',thicknessMm:20,stockLengthMm:3000,stockWidthMm:1600};
const book={approved:true,items:[stock],upstandProfiles:[{id:'P1',reference:'مطابقَة المصنع',sku:'QSTONE',heightMm:100,minCutHeightMm:35}]};
const sillCat={sku:'QSTONE'};
const row={id:'run',tier:'base',wall:'back',start:10,end:230,depth:60,height:86,bottom:0,worktopThicknessMm:40};
const feature=(id,station,width,clear)=>({id,kind:'window',wall:'back',u:station,width,bottom:90+clear/10,height:80,depth:4,swing:'in',hinge:'right',leafWidth:width-4,hingeInset:2});
const doc=(openings,mode='factory')=>({room:{width:380,length:360,height:290,workshop:{upstand:{choice:mode==='factory'?{mode,profileId:'P1'}:{mode,material:'حجر المورد',heightMm:100,thicknessMm:20,minCutHeightMm:35},walls:{}}}},
 kitchen:{features:openings,runs:[row],units:[{id:'a',runId:'run',kind:'storage',u:10,width:100},{id:'b',runId:'run',kind:'storage',u:110,width:120}]}});
const A=feature('A',30,50,60),B=feature('B',100,75,0),C=feature('C',186,35,120);
const d=doc([A,B,C]),take=(d,b=book)=>worktopUpstandTakeoff(d,b);
const s=(v,wall='back')=>v.segments.filter(x=>x.wall===wall).map(x=>[x.fromMm,x.toMm,x.heightMm]);
const w=(v,id)=>v.windows.find(x=>x.windowId===id);
const write=(d,id,input,similar=false,c=book)=>{const result=setUpstandWindowChoice(d,c,w(take(d,c),id).key,input,similar);assert(result.ok,result.reason);return result;};
const proof={kind:'step',clearanceMm:5,reference:'قياس الخلوص عند الإطار والتحقق الفعلي من حركة المقبض',operationChecked:true};
let v=take(d);assert.equal(v.windows.length,3);assert.equal(w(v,'A').status,'pending');assert.equal(w(v,'C').status,'default');assert.equal(w(v,'B').rawClearMm,0);
assert.deepEqual(s(v),[[100,300,100],[800,1000,100],[1750,2300,100]]);
const gap=write(d,'B',{kind:'gap'});assert.equal(w(gap.take,'B').requiredFrom,null);
const step=write(gap.doc,'A',proof);assert.equal(w(step.take,'A').effectiveHeightMm,55);
assert.deepEqual(s(step.take),[[100,300,100],[300,800,55],[800,1000,100],[1750,2300,100]]);
assert(step.take.pieces.some(x=>x.family==='upstand'&&x.a===500&&x.b===55));
const hw=write(gap.doc,'A',{...proof,operationLimitMm:47});assert.equal(w(hw.take,'A').effectiveHeightMm,42);
const noHardwareProof=write(gap.doc,'A',{kind:'step',heightMm:55,clearanceMm:5});
assert.equal(w(noHardwareProof.take,'A').requiredFrom,'rep');assert(noHardwareProof.take.decisionIssues.length);
assert(!noHardwareProof.take.pieces.some(x=>x.b===55));
const oversized=write(gap.doc,'A',{...proof,heightMm:57});assert.equal(w(oversized.take,'A').status,'invalid');
const tooShort=write(gap.doc,'A',{...proof,heightMm:30});assert.equal(w(tooShort.take,'A').requiredFrom,'factory');
const fixed={...book,upstandProfiles:[{...book.upstandProfiles[0],minCutHeightMm:undefined}]};
const unsawn=write(d,'A',proof,false,fixed);assert.equal(w(unsawn.take,'A').requiredFrom,'factory');
const equal=doc([feature('H',40,50,100)]);
assert.equal(w(take(equal),'H').requiredFrom,'rep');assert.deepEqual(s(take(equal)),[[100,2300,100]]);
const cosmetic=write(d,'C',{kind:'gap'});
assert.equal(w(cosmetic.take,'C').status,'resolved');
assert(!s(cosmetic.take).some(([a,b])=>a<1900&&1900<b),'a high window can still receive a deliberate aesthetic gap');
const exact=write(equal,'H',{kind:'step',heightMm:100,clearanceMm:0,reference:'خلوص صفري موثق ومقبول',operationChecked:true},false,fixed);
assert.equal(w(exact.take,'H').effectiveHeightMm,100);
const noZero=write(d,'B',proof);assert.equal(w(noZero.take,'B').requiredFrom,'customer');
const uniform=write(gap.doc,'A',{...proof,kind:'uniform'});assert.equal(w(uniform.take,'C').effectiveHeightMm,55);
assert.deepEqual(s(uniform.take),[[100,1000,55],[1750,2300,55]]);
const reset=write(uniform.doc,'A',null);assert.deepEqual(s(reset.take),s(gap.take));
const similar=doc([A,{...A,id:'A2',u:100},C]);
const bulk=write(similar,'A',proof,true);assert.equal(bulk.applied,2);assert.equal(bulk.skipped,1);assert.equal(w(bulk.take,'A2').status,'pending');
assert.equal(w(bulk.take,'A2').choice.operationChecked,undefined);
const protectedDoc=write(similar,'A2',{kind:'gap'}).doc;
assert.equal(write(protectedDoc,'A',proof,true).applied,1);
const mismatch=write(step.doc,'C',{...proof,kind:'uniform',heightMm:65});assert.equal(w(mismatch.take,'C').status,'invalid');
const autoWall=doc([A,{...A,id:'W2',u:110,bottom:98}]);
const inherited=write(autoWall,'A',{...proof,kind:'uniform',heightMm:50});
assert.equal(w(inherited.take,'W2').requiredFrom,'rep');assert.equal(w(inherited.take,'W2').inheritedUniformHeightMm,50);
const checkedWindow=write(inherited.doc,'W2',{...proof,kind:'uniform'});
assert.deepEqual(s(checkedWindow.take),[[100,2300,50]]);
const twoLow=doc([A,{...A,id:'A2',u:110,bottom:95}]);
const together=write(write(twoLow,'A',{...proof,kind:'uniform'}).doc,'A2',{...proof,kind:'uniform'});
assert.deepEqual(s(together.take),[[100,2300,45]]);
const field=structuredClone(step.doc);field.kitchen.features[0].swing='out';assert.equal(w(take(field),'A').status,'stale');
const moved=structuredClone(step.doc);moved.kitchen.features[0].u+=10;assert.equal(w(take(moved),'A').status,'stale');
const other=structuredClone(step.doc);other.kitchen.features[2].swing='out';assert.equal(w(take(other),'A').status,'resolved');
const orphan=structuredClone(step.doc);orphan.kitchen.features.shift();
const orphanTake=take(orphan);assert.deepEqual(orphanTake.orphanWindows,['back/A/900']);
assert.equal(setUpstandWindowChoice(orphan,book,'back/A/900',null).take.orphanWindows.length,0);
const noSill={kind:'gap',sill:{mode:'factory',...sillCat}};const held=write(gap.doc,'B',noSill);
assert.equal(w(held.take,'B').sillRequiredFrom,'rep');assert.equal(held.take.sills.length,0);
const sill={mode:'factory',sku:stock.sku,depthMm:65,lengthMm:685,insetStartMm:30,reference:'QSILL-checked onsite',verified:true};
const fl=write(step.doc,'B',{kind:'gap',sill});assert.equal(fl.take.sills.length,1);assert.deepEqual(fl.take.sills.map(x=>[x.fromMm,x.toMm,x.bottomMm,x.depthMm]),[[1030,1715,880,65]]);
assert(fl.take.pieces.some(x=>x.family==='windowSill'&&x.sku==='QSTONE'&&x.a===685&&x.b===65));
const changedSillStock={...book,items:[...book.items,{...stock,sku:'SILL-18',thicknessMm:18}]};
const separateStone=write(step.doc,'B',{kind:'gap',sill:{...sill,sku:'SILL-18'}},false,changedSillStock);
const movedGauge={...changedSillStock,items:changedSillStock.items.map(i=>i.sku==='SILL-18'?{...i,thicknessMm:19}:i)};
assert.equal(w(take(separateStone.doc,movedGauge),'B').sillStatus,'stale');
assert.equal(take(separateStone.doc,movedGauge).sills.length,0);
const tooWide=write(step.doc,'B',{kind:'gap',sill:{...sill,lengthMm:740}});assert.equal(tooWide.take.sills.length,0);
const flatHigh=write(step.doc,'A',{kind:'gap',sill});assert.equal(flatHigh.take.sills.length,0);
const ss=doc([B],'supplier');const ext=write(ss,'B',{kind:'gap',sill:{mode:'supplier',material:'حجر منفصل',thicknessMm:15,insetStartMm:0,lengthMm:740,depthMm:65,reference:'QSILL-S',verified:true}});
assert.equal(ext.take.sills[0].mode,'supplier');assert(!ext.take.pieces.length);assert(!ext.take.supplier.some(x=>x.windowId==='B'));
const clone=JSON.parse(JSON.stringify(fl.doc.room.workshop.upstand));assert.deepEqual(cleanUpstandSpec(clone),clone);
assert.equal(cleanUpstandProfiles([{...book.upstandProfiles[0],minCutHeightMm:110}],book.items),null);
assert.equal(cleanUpstandSpec({...clone,windowChoices:{bad:Object.values(clone.windowChoices)[0]}}),null);
assert.equal(previewUpstandWindowChoice(d,book,'unknown',{kind:'gap'}).ok,false);
console.log('Per-window upstand gap, stepped and uniform heights; hardware envelope, material cut limits, protected intent-only copying, stable filed evidence and horizontal recess sill verified.');
