import assert from 'node:assert/strict';
import {makeVisitExample} from './fixture-kitchen-visit-example.mjs';
import {proposeWholeKitchen} from '../public/kitchen-whole-plan.js';
import {customerReport,proposalUnits} from '../public/kitchen-proposal-presentation.js';
import {approvalState} from '../public/kitchen-workshop-state.js';
import {newSurveyProject} from '../public/kitchen-project.js';
import {outputStamp,stampColumns} from '../public/kitchen-output-stamp.js';
import {cleanStudioRoom} from '../public/kitchen-studio-room.js';
const store={getItem:()=>null};
const args={widthMm:5000,lengthMm:5000,heightMm:2800,name:'مشروع'};
const a=newSurveyProject(args,store),b=newSurveyProject(args,store);
assert.match(a.room.projectId,/^K-[A-F0-9]{16}$/);assert.notEqual(a.room.projectId,b.room.projectId);
assert.equal(cleanStudioRoom(a.room).projectId,a.room.projectId);
const base=(await proposeWholeKitchen(makeVisitExample())).candidates[0].doc;
const doc={...base,room:{...base.room,projectId:a.room.projectId}};
const stamp=outputStamp(doc,'المطبخ كاملًا','عرض'),state=await approvalState(doc);
assert.deepEqual(stamp.valid,state.valid);assert.equal(stamp.project,a.room.projectId);
const wall=customerReport({doc,wallIds:['right']});
assert(wall.includes('الوحدات في الرسم · ٠'));assert(wall.includes('سعر هذا النطاق غير محسوب على حدة.'));assert(!wall.includes('قيمة البنود المحسوبة حتى الآن للمطبخ كاملًا'));assert(wall.includes(a.room.projectId)&&wall.includes(stamp.revision));
assert.equal(stampColumns(stamp,['الوحدة'],[['U1']]).rows[0][1],stamp.revision);
assert.equal(stampColumns(stamp,['الوحدة'],[]).rows.length,1);
const moved=structuredClone(doc);moved.kitchen.units[0].width-=1;assert.notEqual(outputStamp(moved,'المطبخ كاملًا','قص').revision,stamp.revision);
assert.equal(outputStamp(doc,'منظور المطبخ','صورة').revision,stamp.revision);
const whole=customerReport({doc});assert(whole.includes('الوحدات في الرسم · '+new Intl.NumberFormat('ar-SA').format(proposalUnits(doc).length)));
const archived=structuredClone(doc);archived.room.photoRefs={back:'off',right:'off',left:'off',front:'off'};
assert.equal(outputStamp(archived,'عرض','صورة').revision,stamp.revision,'Restoring empty background slots must preserve the handoff revision');
console.log('Project identities survive cleanup; scope counts, actual approval state and design revision agree across delivery types, and change with edits.');
