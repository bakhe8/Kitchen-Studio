import assert from 'node:assert/strict';
import {createKitchen,addRun,addFreeRun,addFeature,addUnit,kitchenGeometry,validateKitchen} from '../public/kitchen-model.js';
import {fillKitchenRow} from '../public/kitchen-row-fill.js';
const room={width:500,length:500,height:280};
const ok=r=>(assert.equal(r.ok,true,r.reason),r.kitchen);
const row=(end=240,tier='base')=>ok(addRun(createKitchen(room,'empty'),room,{id:'target',wall:'back',tier,start:0,end}));
const fill=(k,opt={})=>fillKitchenRow(k,room,'target',opt);
const flags=k=>k.units.filter(u=>u.runId==='target').sort((a,b)=>a.u-b.u).map(u=>[u.u,u.width]);
const outcome=fill(row(),{defaults:{frontFinish:'sage'}}),first=ok(outcome),[a,b,c,d]=first.units;
assert.deepEqual(flags(first),[[0,60],[60,60],[120,60],[180,60]]);
assert.equal(outcome.stats.unfilledCm+outcome.stats.blockedCm,0);assert.equal(outcome.stats.filledCm,240);
assert.ok(first.units.every(u=>u.fillRole==='auto'&&u.frontFinish==='sage'));assert.equal(fill(first).kitchen,first);
const changed={...b,width:80};delete changed.fillRole;
const edit=fill({...first,units:[changed]},{previousKitchen:first}),next=ok(edit);
assert.deepEqual(flags(next),[[0,60],[60,80],[140,40],[180,60]]);
assert.equal(next.units.find(u=>u.id===d.id),d);assert.equal(next.units.find(u=>u.id===a.id),a);assert.equal(next.units.find(u=>u.id===c.id).width,40);
assert.equal(next.units.find(u=>u.id===b.id),changed);assert.equal(edit.stats.anchors,1);
const retained={...b,kind:'dishwasher',width:60,fillRole:undefined,frontStyle:undefined,handleStyle:undefined};
const preserved=ok(fill({...first,units:[retained]},{previousKitchen:first}));
assert.equal(preserved.units.find(u=>u.id===b.id),retained);
const gap={u:60,width:60},reserved=ok(fill({...first,runs:first.runs.map(r=>({...r,fillGaps:[gap]})),units:[]},{previousKitchen:first}));
assert.deepEqual(flags(reserved),[[0,60],[120,60],[180,60]]);assert.ok(!reserved.units.some(u=>u.id===b.id));
const clashed={...reserved,units:[retained]};assert.equal(fill(clashed).ok,false);assert.equal(fill(clashed).kitchen,clashed);
const small=ok(addUnit(row(),room,{id:'anchor',kind:'sink',runId:'target',u:10,width:80}));
const partial=fill(small);assert.equal(partial.stats.unfilledCm,10);assert.match(partial.reason,/٢٠/);assert.equal(partial.stats.filledCm,230);
let low=row(320),high=row(320,'upper');
const win={id:'window',kind:'window',wall:'back',u:100,width:90,bottom:120,height:90,depth:4};
low=ok(addFeature(low,room,win));high=ok(addFeature(high,room,win));
assert.equal(fill(low).stats.filledCm,320);
const up=fill(high);assert.equal(up.stats.blockedCm,90);assert.equal(up.stats.filledCm,230);
assert.ok(up.kitchen.units.every(v=>v.u+v.width<=100||v.u>=190));
const door=ok(addFeature(row(),room,{id:'door',kind:'door',wall:'back',u:70,width:90,bottom:0,height:210,swing:'in',hinge:'left'}));
const withDoor=fill(door);assert.equal(withDoor.stats.blockedCm,90);assert.equal(withDoor.stats.filledCm,150);
const none=ok(addFeature(row(80),room,{id:'door',kind:'door',wall:'back',u:0,width:80,bottom:0,height:200}));
assert.equal(fill(none).ok,false);assert.equal(fill(none).kitchen,none);
const empty=createKitchen(room,'empty'),isl=ok(addFreeRun(empty,room,{id:'target',x:160,z:140,length:180,angle:28,depth:58}));assert.equal(fill(isl).stats.filledCm,180);
// Face-to-face rows leave only 35 cm in front. A 60 cm hinged leaf would
// hit the island; pairs of modeled half-width leaves open without collision.
let face=row(240);face=ok(addFreeRun(face,room,{id:'face',x:0,z:95,length:240,angle:0,depth:60}));
face=ok(addUnit(face,room,{id:'across',runId:'face',kind:'open-shelf',u:0,width:240}));
const compact=ok(fill(face));assert.ok(compact.units.filter(x=>x.runId==='target').every(x=>x.doorHanding==='pair'));
const doorsOpen=kitchenGeometry({...compact,units:compact.units.map(u=>({...u,open:u.kind!=='open-shelf'}))},room);
assert.ok(!doorsOpen.conflicts.some(c=>c.type==='open-body'&&c.ids.includes('across')));
const narrow=row(67.3),custom=ok(fill(narrow));assert.deepEqual(flags(custom),[[0,67.3]]);
assert.ok(validateKitchen(next,room));
console.log('Row completion: exact and fractional spans, local locked edit and ID stability, fixed appliance, reserved bays, narrow residual disclosure, upper/base sill difference, inward door, rotated island and single-door opening against opposing units.');
